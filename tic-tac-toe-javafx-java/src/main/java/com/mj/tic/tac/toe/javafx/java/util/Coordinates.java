package com.mj.tic.tac.toe.javafx.java.util;

public final class Coordinates {

    private final int x;

    private final int y;

    public Coordinates(int x, int y) {
        this.x = x;
        this.y = y;
    }

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }
}
